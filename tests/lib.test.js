const L = require(require('path').join(__dirname, '..', 'extension', 'lib.js'));
const assert = require('assert');
const h = (o) => Object.entries(o).map(([name, value]) => ({ name, value }));
assert.deepStrictEqual(L.classify('https://a.com/v/master.m3u8?t=1', h({'content-type':'application/vnd.apple.mpegurl'})), {kind:'manifest',type:'HLS',size:null});
assert.strictEqual(L.classify('https://a.com/s/manifest.mpd', h({})).type, 'DASH');
assert.strictEqual(L.classify('https://a.com/seg1.ts', h({'content-type':'video/mp2t'})), null);
assert.strictEqual(L.classify('https://a.com/x.m4s', h({})), null);
assert.strictEqual(L.classify('https://a.com/clip.mp4', h({'content-type':'video/mp4','content-length':'5000000'})).size, 5000000);
assert.strictEqual(L.classify('https://a.com/tiny.mp4', h({'content-type':'video/mp4','content-length':'1000'})), null);
assert.strictEqual(L.classify('https://a.com/page.html', h({'content-type':'text/html'})), null);
assert.strictEqual(L.classify('https://rr1.googlevideo.com/videoplayback?x=1', h({'content-type':'video/mp4','content-length':'9999999'})), null);
assert.strictEqual(L.classify('http://127.0.0.1:6800/add', h({'content-type':'video/mp4'})), null);
assert.strictEqual(L.classify('blob:https://a.com/1', h({})), null);
assert.strictEqual(L.classify('https://a.com/stream', h({'content-type':'audio/mpeg','content-range':'bytes 0-99/7000000'})).size, 7000000);
assert.strictEqual(L.pickBest([{kind:'file',size:5},{kind:'manifest',url:'m'},{kind:'file',size:9}]).url, 'm');
assert.strictEqual(L.pickBest([{kind:'file',size:5,url:'a'},{kind:'file',size:9,url:'b'}]).url, 'b');
assert.strictEqual(L.dedupeKey('https://a.com/p.m3u8?token=1','manifest'), 'https://a.com/p.m3u8');
assert.strictEqual(L.fmtSize(1536), '1.5 KB');
assert.strictEqual(L.pageVideo('https://www.youtube.com/watch?v=QqumyKqzl4s'), 'YouTube');
assert.strictEqual(L.pageVideo('https://youtu.be/abc'), 'YouTube');
assert.strictEqual(L.pageVideo('https://www.youtube.com/'), null);
assert.strictEqual(L.pageVideo('https://vimeo.com/12345'), 'Vimeo');
assert.strictEqual(L.pageVideo('https://example.com/watch?v=1'), null);
console.log('lib tests passed');
